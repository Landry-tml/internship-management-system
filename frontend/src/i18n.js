const englishTranslations = Object.fromEntries(
  Object.entries(frenchTranslations).map(([english, french]) => [french, english])
);

function translateText(text, language) {
  if (!text) return text;
  const translations = language === 'fr' ? frenchTranslations : englishTranslations;
  const trimmed = text.trim();
  const translation = translations[trimmed];
  if (translation) return text.replace(trimmed, translation);

  const prefixes = Object.keys(translations)
    .filter((phrase) => phrase.endsWith(':') || phrase.endsWith(',') || phrase.endsWith(' '))
    .map((phrase) => ({ key: phrase, prefix: phrase.trimEnd() }))
    .sort((left, right) => right.prefix.length - left.prefix.length);
  const matchedPrefix = prefixes.find(({ prefix }) => trimmed.startsWith(prefix) &&
    (trimmed.length === prefix.length || /\s/.test(trimmed[prefix.length])));
  const prefix = matchedPrefix?.key;
  if (!prefix) return text;
  return text.replace(trimmed, `${translations[prefix].trimEnd()}${trimmed.slice(matchedPrefix.prefix.length)}`);
}

export function localizeApplication(root, language) {
  if (!root) return;
  const textWalker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let textNode;
  while ((textNode = textWalker.nextNode())) {
    const translated = translateText(textNode.nodeValue, language);
    if (translated !== textNode.nodeValue) textNode.nodeValue = translated;
  }

  root.querySelectorAll('[placeholder], [title], [aria-label]').forEach((element) => {
    ['placeholder', 'title', 'aria-label'].forEach((attribute) => {
      const value = element.getAttribute(attribute);
      const translated = translateText(value, language);
      if (translated !== value) element.setAttribute(attribute, translated);
    });
  });
}
